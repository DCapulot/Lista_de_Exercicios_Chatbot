import re


respostas = {
    "saudacao": "Olá, {nome}! Como posso ajudar?",
    "horario": "Nosso horário é de segunda a sexta, das 9h às 18h.",
    "contato": "Nosso contato é suporte@empresa.com.",
    "despedida": "Até logo, {nome}!"
}


def identificar_intencao(mensagem):
    if re.search(r"\b(oi|olá|ola|bom dia|boa tarde)\b", mensagem):
        return "saudacao"

    elif re.search(r"\b(horário|horario|abre|fecha|funciona)\b", mensagem):
        return "horario"

    elif re.search(r"\b(contato|telefone|email|falar)\b", mensagem):
        return "contato"

    elif re.search(r"\b(tchau|adeus|sair|encerrar)\b", mensagem):
        return "despedida"

    return None


def chatbot():
    nome = input("Bot: Qual é o seu nome?\nVocê: ").strip()

    estado = "menu"

    while estado != "encerrado":

        if estado == "menu":

            print("\n===== MENU =====")
            print("1 - Saudação")
            print("2 - Horário")
            print("3 - Contato")
            print("4 - Sair")

            mensagem = input("\nVocê: ").lower().strip()

            if mensagem == "4":
                estado = "encerrado"

            elif mensagem in ["1", "2", "3"]:
                if mensagem == "1":
                    intencao = "saudacao"
                elif mensagem == "2":
                    intencao = "horario"
                else:
                    intencao = "contato"

                print("Bot:", respostas[intencao].format(nome=nome))

            else:
                intencao = identificar_intencao(mensagem)

                if intencao == "despedida":
                    print("Bot:", respostas[intencao].format(nome=nome))
                    estado = "encerrado"

                elif intencao:
                    print("Bot:", respostas[intencao].format(nome=nome))

                else:
                    print("Bot: Não entendi. Escolha uma opção do menu.")

    print("Bot: Chatbot encerrado. Obrigado pelo contato!")


