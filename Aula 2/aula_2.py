import re

regras = [
    {
        "padrao": r"\b(oi|olá|ola)\b",
        "resposta": "Olá! Como posso ajudar?"
    },
    {
        "padrao": r"\b(preço|preco|valor)\b",
        "resposta": "Consulte nosso site."
    },
    {
        "padrao": r"\b(tchau|sair|adeus)\b",
        "resposta": "Até logo!"
    }
]


def identificar_resposta(mensagem):
    for regra in regras:
        if re.search(regra["padrao"], mensagem):
            return regra["resposta"]

    return "Não entendi sua mensagem."


def chatbot():
    while True:
        mensagem = input("Você: ").lower().strip()

        resposta = identificar_resposta(mensagem)

        print("Bot:", resposta)

        if re.search(r"\b(tchau|sair|adeus)\b", mensagem):
            break


